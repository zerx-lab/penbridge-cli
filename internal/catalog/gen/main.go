// Command gen parses a SiYuan kernel/api/router.go file and emits a Go source
// file containing the full endpoint catalog.
//
// Usage:
//
//	go run ./gen <path-to-router.go> <output.go>
package main

import (
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
)

var (
	reHandle = regexp.MustCompile(`ginServer\.Handle\(\s*"([A-Z]+)"\s*,\s*"([^"]+)"\s*,(.*)\)`)
	reAny    = regexp.MustCompile(`ginServer\.Any\(\s*"([^"]+)"\s*,(.*)\)`)
)

type endpoint struct {
	Method     string
	Path       string
	Category   string
	Name       string
	Auth       bool
	Admin      bool
	Write      bool
	Deprecated bool
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: go run ./gen <router.go> <output.go>")
		os.Exit(2)
	}
	in, out := os.Args[1], os.Args[2]
	data, err := os.ReadFile(in)
	if err != nil {
		fmt.Fprintln(os.Stderr, "read:", err)
		os.Exit(1)
	}

	byPath := map[string]*endpoint{}
	for _, line := range strings.Split(string(data), "\n") {
		var method, path, mids string
		if m := reHandle.FindStringSubmatch(line); m != nil {
			method, path, mids = m[1], strings.TrimSpace(m[2]), m[3]
		} else if m := reAny.FindStringSubmatch(line); m != nil {
			method, path, mids = "POST", strings.TrimSpace(m[1]), m[2]
		} else {
			continue
		}
		if !strings.HasPrefix(path, "/api/") {
			continue // skip /ws, /es, /stage, etc.
		}
		ep := &endpoint{
			Method:     method,
			Path:       path,
			Auth:       strings.Contains(mids, "CheckAuth"),
			Admin:      strings.Contains(mids, "CheckAdminRole"),
			Write:      strings.Contains(mids, "CheckReadonly"),
			Deprecated: strings.Contains(mids, "deprecated"),
		}
		ep.Category, ep.Name = split(path)
		if existing, ok := byPath[path]; ok {
			// Prefer POST when a path has multiple methods.
			if existing.Method != "POST" && method == "POST" {
				existing.Method = "POST"
			}
			continue
		}
		byPath[path] = ep
	}

	eps := make([]*endpoint, 0, len(byPath))
	for _, e := range byPath {
		eps = append(eps, e)
	}
	sort.Slice(eps, func(i, j int) bool { return eps[i].Path < eps[j].Path })

	var b strings.Builder
	b.WriteString("// Code generated by internal/catalog/gen; DO NOT EDIT.\n\n")
	b.WriteString("package catalog\n\n")
	fmt.Fprintf(&b, "// endpoints contains %d SiYuan kernel API routes.\n", len(eps))
	b.WriteString("var endpoints = []Endpoint{\n")
	for _, e := range eps {
		fmt.Fprintf(&b,
			"\t{Method: %q, Path: %q, Category: %q, Name: %q, Auth: %t, Admin: %t, Write: %t, Deprecated: %t},\n",
			e.Method, e.Path, e.Category, e.Name, e.Auth, e.Admin, e.Write, e.Deprecated)
	}
	b.WriteString("}\n")

	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "write:", err)
		os.Exit(1)
	}
	fmt.Printf("wrote %d endpoints to %s\n", len(eps), out)
}

func split(path string) (category, name string) {
	parts := strings.Split(strings.Trim(path, "/"), "/")
	// parts[0] == "api"
	switch {
	case len(parts) >= 3:
		return parts[1], parts[len(parts)-1]
	case len(parts) == 2:
		return parts[1], parts[1]
	default:
		return "misc", path
	}
}
